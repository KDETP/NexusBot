module.exports = {

    info(message) {
        console.log(`[INFO] ${message}`);
    },

    success(message) {
        console.log(`[SUCCESS] ${message}`);
    },

    warning(message) {
        console.log(`[WARNING] ${message}`);
    },

    error(message) {
        console.log(`[ERROR] ${message}`);
    }

};